const approved = (role: 'Project manager' | 'Head of Finance', approver: string, at: string, note = '') => ({
  role,
  approver,
  decision: 'approved' as const,
  note,
  at,
})
const pending = (role: 'Project manager' | 'Head of Finance', approver: string) => ({
  role,
  approver,
  decision: 'pending' as const,
  note: '',
  at: null,
})
const noSync = () => ({ synced: false, at: null, reference: null, log: [] })
const synced = (at: string, reference: string) => ({
  synced: true,
  at,
  reference,
  log: [
    { at, text: `Posted to ERP as ${reference}. Committed cost recorded against the project.` },
  ],
})

