type AuditSeed = [at: string, who: string, action: string]
const audit = (entries: AuditSeed[]) =>
  entries.map(([at, who, action], i) => ({ id: `a${i}-${at}`, at, who, action }))

const line = (id: string, description: string, qty: number, unitPrice: number) => ({
  id,
  description,
  qty,
  unitPrice,
})

